# A program to perform mathematical operations between two values using python.

def func(a,b):
    add=a+b
    print(f"The addition of the two numbers {a} and {b} are: ",add)
    sub=a-b
    print(f"The subtraction of the two numbers {a} and {b} are: ",sub)
    mult=a*b
    print(f"The multiplication of the two numbers {a} and {b} are: ",mult)
    div=a/b
    print(f"The division of the two numbers {a} and {b} are: ",div)
    mod=a%b
    print(f"The modulud of the two numbers {a} and {b} are: ",mod)
    
func(8,3)
